#!/usr/bin/env python3
# Regenerates internal/content/mimes_gen.go from Trilium's mime_type.ts:
#   curl -sL https://raw.githubusercontent.com/TriliumNext/Trilium/main/packages/commons/src/lib/mime_type.ts -o /tmp/mime_type.ts
#   python3 scripts/gen_mimes.py /tmp/mime_type.ts > internal/content/mimes_gen.go && gofmt -w internal/content/mimes_gen.go
import re,sys
src=open(sys.argv[1]).read()
body=src[src.index('MIME_TYPES_DICT_RAW = ['):src.index('] as const')]
entries=[]
for m in re.finditer(r'\{([^{}]*)\}',body):
    e=m.group(1)
    mime=re.search(r'mime: "([^"]+)"',e).group(1)
    md=re.search(r'mdLanguageCode: "([^"]+)"',e)
    al=re.search(r'aliases: \[([^\]]*)\]',e)
    aliases=re.findall(r'"([^"]+)"',al.group(1)) if al else []
    entries.append((mime,md.group(1) if md else None,aliases))
names={}
for mime,md,al in entries:
    for a in al: names[a]=mime
for mime,md,al in entries:
    if md and md not in names: names[md]=mime
ext=dict(re.findall(r'^\s+(\w+): "(\w+)",?$',src[src.index('LANGUAGES_BY_EXTENSION'):],re.M))
print("// Code generated by scripts/gen_mimes.py from Trilium's mime_type.ts. DO NOT EDIT.\n")
print("package content\n")
print("// markdownNames mirrors getMimeTypeFromMarkdownName(): aliases win over mdLanguageCode,")
print("// and the first entry wins among equal mdLanguageCodes.")
print("var markdownNames = map[string]string{")
for k in sorted(names): print(f'\t"{k}": "{names[k]}",')
print("}\n")
print("// languagesByExtension mirrors LANGUAGES_BY_EXTENSION.")
print("var languagesByExtension = map[string]string{")
for k in sorted(ext): print(f'\t"{k}": "{ext[k]}",')
print("}")
